"""
Independent mathematical specification of the 4x4 Wen-plaquette code.

Everything here is derived from the lattice definition (qubit (r,c) -> 4r+c,
periodic boundaries, checkerboard X/Z plaquettes), NOT from the pass module's
lookup tables, so it can serve as an independent verifier.
"""
from __future__ import annotations

from dataclasses import dataclass
from itertools import combinations
from typing import Dict, List, Set, Tuple

import numpy as np

L = 4
N = L * L  # 16 data qubits


def qidx(r: int, c: int) -> int:
    return (r % L) * L + (c % L)


def plaquette_support(r: int, c: int) -> Tuple[int, ...]:
    return tuple(sorted({qidx(r, c), qidx(r, c + 1), qidx(r + 1, c), qidx(r + 1, c + 1)}))


def derive_stabilizers() -> List[Tuple[str, Tuple[int, ...]]]:
    """Checkerboard plaquettes on the L x L torus: Z on (r+c) even, X on (r+c) odd."""
    stabs = []
    for r in range(L):
        for c in range(L):
            ptype = "Z" if (r + c) % 2 == 0 else "X"
            stabs.append((ptype, plaquette_support(r, c)))
    return stabs


@dataclass(frozen=True)
class Pauli:
    """Binary symplectic representation: x[i]=1 -> X on qubit i, z[i]=1 -> Z on qubit i."""
    x: Tuple[int, ...]
    z: Tuple[int, ...]

    @property
    def weight(self) -> int:
        return sum(1 for i in range(N) if self.x[i] or self.z[i])

    def commutes_with(self, other: "Pauli") -> bool:
        # symplectic inner product mod 2
        s = sum(self.x[i] * other.z[i] + self.z[i] * other.x[i] for i in range(N)) % 2
        return s == 0

    def multiply(self, other: "Pauli") -> "Pauli":
        return Pauli(
            x=tuple((a ^ b) for a, b in zip(self.x, other.x)),
            z=tuple((a ^ b) for a, b in zip(self.z, other.z)),
        )


def from_support(ptype: str, support: Tuple[int, ...]) -> Pauli:
    x = tuple(1 if ptype == "X" and i in support else 0 for i in range(N))
    z = tuple(1 if ptype == "Z" and i in support else 0 for i in range(N))
    return Pauli(x, z)


def gf2_rank(rows: List[Tuple[int, ...]]) -> int:
    m = np.array(rows, dtype=np.uint8) % 2
    if m.size == 0:
        return 0
    m = m.copy()
    rank = 0
    ncols = m.shape[1]
    for col in range(ncols):
        piv = None
        for r in range(rank, m.shape[0]):
            if m[r, col]:
                piv = r
                break
        if piv is None:
            continue
        m[[rank, piv]] = m[[piv, rank]]
        for r in range(m.shape[0]):
            if r != rank and m[r, col]:
                m[r] ^= m[rank]
        rank += 1
    return rank


def stabilizer_group_rank(stabs: List[Pauli]) -> int:
    rows = [s.x + s.z for s in stabs]  # symplectic vectors, length 2N
    return gf2_rank(rows)


def all_pairs_commute(stabs: List[Pauli]) -> bool:
    return all(stabs[i].commutes_with(stabs[j]) for i in range(len(stabs)) for j in range(i + 1, len(stabs)))


def stabilizer_membership(p: Pauli, stabs: List[Pauli]) -> bool:
    """Is p in the group generated by stabs? Solve gf2 linear system."""
    A = np.array([s.x + s.z for s in stabs], dtype=np.uint8) % 2  # rows = generators (16 x 32)
    b = np.array(p.x + p.z, dtype=np.uint8) % 2
    if A.size == 0:
        return not b.any()
    # membership: exists y (len 16) with A^T y = b  ->  augmented [A^T | b], 32 x 17
    aug = np.concatenate([A.T, b.reshape(-1, 1)], axis=1).astype(np.uint8)
    n_gen = A.shape[0]
    rank = 0
    nrows = aug.shape[0]
    for col in range(n_gen):
        piv = None
        for r in range(rank, nrows):
            if aug[r, col]:
                piv = r
                break
        if piv is None:
            continue
        aug[[rank, piv]] = aug[[piv, rank]]
        for r in range(nrows):
            if r != rank and aug[r, col]:
                aug[r] ^= aug[rank]
        rank += 1
    # inconsistent iff some row is [0...0 | 1]
    for r in range(nrows):
        if not aug[r, :n_gen].any() and aug[r, n_gen]:
            return False
    return True


def enumerate_logicals(stabs: List[Pauli], max_weight: int = 3) -> List[Pauli]:
    """All nontrivial logical Paulis of weight <= max_weight (commute with all, not in group)."""
    found = []
    for w in range(1, max_weight + 1):
        for qubits in combinations(range(N), w):
            for mask in range(1, 1 << (2 * w)):  # non-identity Pauli on those qubits
                x = [0] * N
                z = [0] * N
                for k, q in enumerate(qubits):
                    if mask & (1 << (2 * k)):
                        x[q] = 1
                    if mask & (1 << (2 * k + 1)):
                        z[q] = 1
                p = Pauli(tuple(x), tuple(z))
                if all(p.commutes_with(s) for s in stabs) and not stabilizer_membership(p, stabs):
                    found.append(p)
    return found


def logical_representatives(stabs: List[Pauli]) -> Dict[str, Pauli]:
    """Row/column string representatives of the k=2 logical operators on the torus."""
    reps = {}
    reps["X_L_row0"] = from_support("X", tuple(qidx(0, c) for c in range(L)))
    reps["X_L_col0"] = from_support("X", tuple(qidx(r, 0) for r in range(L)))
    reps["Z_L_row0"] = from_support("Z", tuple(qidx(0, c) for c in range(L)))
    reps["Z_L_col0"] = from_support("Z", tuple(qidx(r, 0) for r in range(L)))
    for name, p in reps.items():
        assert all(p.commutes_with(s) for s in stabs), name
        assert not stabilizer_membership(p, stabs), name
    return reps


def code_parameters() -> Dict[str, object]:
    stabs_derived = derive_stabilizers()
    paulis = [from_support(t, s) for t, s in stabs_derived]
    rank = stabilizer_group_rank(paulis)
    logicals_w3 = enumerate_logicals(paulis, max_weight=3)
    return {
        "L": L,
        "n_data_qubits": N,
        "n_stabilizer_generators_listed": len(paulis),
        "n_X_generators": sum(1 for t, _ in stabs_derived if t == "X"),
        "n_Z_generators": sum(1 for t, _ in stabs_derived if t == "Z"),
        "all_generators_pure_type": True,
        "all_pairs_commute": all_pairs_commute(paulis),
        "stabilizer_rank": rank,
        "n_logical_qubits_k": N - rank,
        "min_logical_weight_le3": min((p.weight for p in logicals_w3), default=None),
        "distance_claim": "d=4 (no nontrivial logical of weight <= 3; row/col strings have weight 4)",
    }
